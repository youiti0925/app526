/**
 * 副業案件の危険シグナル。
 *
 * 出典の考え方: 国民生活センター・消費者庁が繰り返し注意喚起している
 * 「副業儲け話」「情報商材」「タスク詐欺」の典型手口と、警察庁が示す
 * 闇バイトの募集文言、および特定商取引法・金融商品取引法・犯罪収益移転
 * 防止法に照らして違法/違法の疑いが濃い要求を、重み付きルールにしたもの。
 *
 * weight は 1-10。10 は「これ単体で関わってはいけない」レベル。
 */
export interface ScamRule {
  id: string;
  label: string;
  weight: number;
  why: string;
  /** 本文にマッチさせる正規表現。ひとつでも当たれば発火。 */
  patterns: RegExp[];
  /**
   * 全部にマッチしたときだけ発火する条件。
   * 単独では普通の案件にも出る語（「面談」「シグナル」など）を、
   * 組み合わせで初めて危険と見なすために使う。
   */
  /**
   * 追加条件。指定した場合、patterns が当たったうえで**全部**当たったときだけ発火する。
   * patterns が空のルールでは、これ単体が発火条件になる。
   */
  requireAll?: RegExp[];
  /** 発火時に追加で出す具体的な行動指示 */
  action?: string;
}

