/**
 * 本文に「あるべきものが無い」ことで発火する検査。
 *
 * 特商法の表記義務は「読み手が金を払う側」のときにだけ意味を持つ。
 * 報酬を受け取る側である普通の求人票に対して発火させると、
 * まっとうな案件が軒並み要注意になり、警告そのものが無視されるようになる。
 * だから「こちらが払う構造」が検出されているときに限って発火させる。
 */
function checkAbsence(text: string, firedIds: Set<string>): ScamSignalHit[] {
  const hits: ScamSignalHit[] = [];

  const readerPays =
    firedIds.has("upfront_payment") ||
    firedIds.has("high_ticket_backend") ||
    firedIds.has("inventory_purchase") ||
    /(ご購入|お申込み|受講料|参加費|販売価格|価格は|料金プラン|お求め)/.test(text);

  const hasLegalDisclosure =
    /(特定商取引法|特商法|運営者情報|会社概要|所在地|法人番号)/.test(text);

  if (readerPays && !hasLegalDisclosure) {
    const rule = SCAM_RULES.find((r) => r.id === "no_legal_disclosure");
    if (rule) {
      hits.push({
        id: rule.id,
        label: rule.label,
        weight: rule.weight,
        why: rule.why,
      });
    }
  }
  return hits;
}

export interface ScamScoreResult {
  score: number;
  verdict: "safe" | "caution" | "danger";
  signals: ScamSignalHit[];
  advice: string;
}

/** 本文中のマッチ箇所を、前後を少し含めて抜き出す。 */
function excerptAround(text: string, index: number, length: number): string {
  const start = Math.max(0, index - 15);
  const end = Math.min(text.length, index + length + 15);
  return (start > 0 ? "…" : "") + text.slice(start, end).replace(/\s+/g, " ") + (end < text.length ? "…" : "");
}

/**
 * ルールベースのスコアリング。APIキー無しでも必ず動く。
 *
 * スコアは「発火した重みの合計」を 0-100 に圧縮したもの。重み 10 の
 * ルールが 1 本でも当たれば、それだけで danger 相当になるようにしている。
 */
export function scoreScam(text: string): ScamScoreResult {
  const normalized = text.normalize("NFKC");
  const signals: ScamSignalHit[] = [];

  for (const rule of SCAM_RULES) {
    let match: RegExpMatchArray | null = null;

    // requireAll は「patterns に加えて全部当たること」を求める追加条件。
    // ここを OR にしていたせいで、patterns が1つも当たっていない普通のIT案件が
    // 「詐欺スコア70」で落ちていた（「個別説明会」と「安定稼働」の"稼"だけで発火）。
    const gateOk =
      !rule.requireAll ||
      rule.requireAll.length === 0 ||
      rule.requireAll.every((pattern) => {
        const m = normalized.match(pattern);
        return m !== null && m.index !== undefined;
      });

    if (gateOk) {
      if (rule.patterns.length === 0) {
        // patterns を持たないルールは、requireAll 自体が発火条件
        match = rule.requireAll ? normalized.match(rule.requireAll[0]) : null;
      } else {
        for (const pattern of rule.patterns) {
          const found = normalized.match(pattern);
          if (found && found.index !== undefined) {
            match = found; // 同一ルールは1回だけ数える
            break;
          }
        }
      }
    }

    if (match && match.index !== undefined) {
      signals.push({
        id: rule.id,
        label: rule.label,
        weight: rule.weight,
        why: rule.action ? `${rule.why}\n→ ${rule.action}` : rule.why,
        excerpt: excerptAround(normalized, match.index, match[0].length),
      });
    }
  }

  signals.push(...checkAbsence(normalized, new Set(signals.map((s) => s.id))));

  return combineSignals(signals);
}

/**
 * 発火したシグナル群からスコアと判定を組み立てる。
 * AI が追加したシグナルを混ぜて再計算するときも同じ関数を通す。
 */
export function combineSignals(signals: ScamSignalHit[]): ScamScoreResult {
  const weightSum = signals.reduce((sum, s) => sum + s.weight, 0);
  const maxWeight = signals.reduce((max, s) => Math.max(max, s.weight), 0);

  // 合計だけだと「弱いシグナル多数」が「致命的なもの1本」を超えてしまうので、
  // 最大重みの単独寄与を保証する。
  const fromSum = Math.min(70, weightSum * 4);
  const fromMax = maxWeight >= 10 ? 85 : maxWeight >= 9 ? 70 : maxWeight >= 8 ? 55 : maxWeight * 5;
  const score = Math.min(100, Math.round(Math.max(fromSum, fromMax)));

  const verdict: ScamScoreResult["verdict"] = score >= 60 ? "danger" : score >= 25 ? "caution" : "safe";

  return { score, verdict, signals, advice: buildAdvice(verdict, signals) };
}

