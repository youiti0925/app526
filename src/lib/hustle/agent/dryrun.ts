import { readProfile } from "../db";
import { getGenreTarget, type DryRun } from "./dryrun-core";

export * from "./dryrun-core";

// ---------------------------------------------------------------------------
// 指示書
// ---------------------------------------------------------------------------

/**
 * 「この案件を受けたつもりで、実際に成果物を作れ」という指示書。
 *
 * 見本やサンプルではなく、納品できる状態のものを作らせる。
 * 手を抜いた成果物を採点しても、能力の検証にならない。
 */
export function buildProduceBrief(runs: DryRun[]): string {
  const profile = readProfile();

  const header = `# 試作の依頼（実際に成果物を作ってください）

これは練習ではありません。**実在する募集**に対して、実際に納品する成果物を作ります。
目的は、このアプリが「AIで納品物を作れる」と主張している範囲が本当かどうかを確かめることです。

## 守ってほしいこと

1. **見本やサンプルで済ませないでください。** 「〜のような構成で書けます」ではなく、
   実際に書いてください。分量が多い場合は、全体の構成を示したうえで、
   代表的な1セクションを納品できる密度まで作り込んでください。

2. **できなかったら「できなかった」と書いてください。** 無理に何か出すより、
   何が足りなかったのかを具体的に書くほうが価値があります。
   blocked に理由を書いて、artifact は空で構いません。

3. **事実を創作しないでください。** 数字・法令・企業名・実績は、
   確認できたものだけを書いてください。確認できないものは
   【要確認: 何を確認するか】 の形で残してください。

4. **使った手段を全部書いてください。** どのツール、どのコマンド、
   どの無料枠を使ったか。商用利用が許諾されているかも確認してください。
   ここが後で「その手段は規約違反だった」となると、全部やり直しになります。

5. **人がやらないと終わらない工程を分けてください。**
   あなたが出せるところまでと、その後で人が何時間かける必要があるかを書いてください。

## 作業する人の前提

- 経歴: ${profile?.background || "（未入力）"}
- 使える時間: 週 ${profile?.weeklyHours ?? 10} 時間
- 元手: ${(profile?.budgetJpy ?? 0).toLocaleString()} 円（**有料ツールは使えません**。無料枠のみ）

## 出力

次の形の JSON **だけ** を返してください。

\`\`\`json
{
  "results": [
    {
      "dryRunId": "下の各案件に書いてあるIDをそのまま",
      "artifact": "作った成果物そのもの。長い場合はそのまま全部入れてください。",
      "method": "どうやって作ったか。使ったツール・コマンド・無料枠・商用利用の可否。",
      "humanStepsLeft": ["納品までに人がやる必要がある工程"],
      "humanHoursLeft": 数値,
      "blocked": "作れなかった場合の理由。作れたなら空文字。",
      "selfDoubt": "自分の成果物で一番危ういと思う点。ここを正直に書いてください。"
    }
  ]
}
\`\`\`

---

`;

  const body = runs
    .map((run, i) => {
      const target = getGenreTarget(run.genre);
      return `## 試作 ${i + 1}: ${target?.label ?? run.genre}

- dryRunId: \`${run.id}\`
- いまのアプリの主張: **${target?.claim === "can" ? "この納品物は作れる" : "この納品物は作れない"}**
- 検証したいこと: ${target?.probe ?? "この案件の成果物を作ってください。"}
${run.sourceUrl ? `- 元の募集: ${run.sourceUrl}` : ""}

### 募集の内容

\`\`\`
${run.requirement.slice(0, 5000)}
\`\`\`
`;
    })
    .join("\n---\n\n");

  return header + body;
}

/**
 * 採点の指示書。
 *
 * 作った本人には採点させない。自分の出力は良く見えるので、
 * 「そのまま納品できます」が返ってきてしまう。
 * 依頼者の立場で、金を払う価値があるかを見る。
 */
export function buildGradeBrief(runs: DryRun[]): string {
  const header = `# 成果物の採点

AIが作った成果物を採点してください。**あなたは依頼者側の人間です。**
これに金を払うか、突き返すかを決める立場で見てください。

## 採点の基準

1. **募集が求めているものになっているか。** 見た目が整っていても、
   聞かれていないことに答えているなら不合格です。

2. **事実の誤りがないか。** 一番危ないのは、もっともらしく書かれた誤りです。
   法令名・数値・規格番号・企業名は、実際に確認してください。
   確認できないものが混ざっていたら needsFactCheck に入れてください。

3. **そのまま出せるか。** 「手を入れれば使える」は needs_work です。
   pass は「このまま依頼者に渡せる」場合だけにしてください。

4. **人があと何時間かかるか。** ここを小さく見積もると、
   受注したあとに時給が崩壊します。多めに見てください。

5. **手段が規約上問題ないか。** 生成に使ったツールの商用利用が
   許諾されていない場合、成果物の出来に関係なく fail です。

甘い点をつけないでください。ここで甘くすると、実際の案件で
「納品できます」と言って受注し、納品できずに信用を失います。

## 出力

次の形の JSON **だけ** を返してください。

\`\`\`json
{
  "grades": [
    {
      "dryRunId": "下の各成果物に書いてあるIDをそのまま",
      "meetsRequirement": 0から100の数値,
      "deliverable": true または false,
      "gaps": ["足りていない点"],
      "humanHoursNeeded": 数値,
      "needsFactCheck": ["裏取りが必要な記述"],
      "verdict": "pass" | "needs_work" | "fail" | "cannot_produce",
      "reason": "その判定にした理由。1〜3文。"
    }
  ]
}
\`\`\`

---

`;

  const body = runs
    .map((run, i) => {
      const target = getGenreTarget(run.genre);
      return `## 成果物 ${i + 1}: ${target?.label ?? run.genre}

- dryRunId: \`${run.id}\`
- 特に見てほしい点: ${(target?.gradeFocus ?? []).join(" / ")}
- 作った手段: ${run.method || "（未記入）"}
${run.blockedReason ? `- 作れなかった理由: ${run.blockedReason}` : ""}

### 元の募集

\`\`\`
${run.requirement.slice(0, 3000)}
\`\`\`

### 提出された成果物

\`\`\`
${run.artifact.slice(0, 12_000) || "（成果物なし）"}
\`\`\`
`;
    })
    .join("\n---\n\n");

  return header + body;
}

